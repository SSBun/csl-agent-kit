const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const repo = '/Users/caishilin/Desktop/personal/skills';
const root = fs.mkdtempSync(path.join(os.tmpdir(), 'memory-commit-walkthrough-'));
process.env.CSL_AGENT_KIT_HOME = path.join(root, 'home');
const workspace = path.join(root, 'project-a');
const other = path.join(root, 'project-b');
fs.mkdirSync(workspace); fs.mkdirSync(other);
const queue = require(repo + '/bin/memory/queue.js');
const runtime = require(repo + '/bin/memory/runtime-files.js');
const store = require(repo + '/bin/memory/store.js');
const commits = require(repo + '/bin/memory/commits.js');
const maintenance = require(repo + '/bin/memory/maintenance.js');
const event = (key, ws = workspace) => ({schema:'csl-memory-event/v1',workspace:ws,session:'walkthrough',eventKey:key,messages:[{role:'user',text:'隔离走查输入，不是真实用户记忆'}]});
const report = (stage, result) => console.log(JSON.stringify({stage,...result}));
const mutation = (id, retrieval) => ({id,operation:'put',expected:{revision:0,hash:null},reason:'隔离手工走查',source:'walkthrough',session:'walkthrough',content:{title:id,summary:'仅供隔离走查',type:'fact',sources:['walkthrough'],body:'隔离资料；不进入真实记忆。',...(retrieval ? {retrieval} : {})}});
const original = event('no-change');
const first = queue.enqueue(original);
queue.complete(first.id);
report('无变更完成', {eventExists:fs.existsSync(runtime.file(`events/${first.id}.json`)),jobExists:fs.existsSync(runtime.file(`jobs/${first.id}.json`)),receipt:queue.get(first.id),duplicate:queue.enqueue(original),pending:queue.list().total,commits:commits.list().total});
try { queue.enqueue({...original,messages:[{role:'user',text:'不同输入'}]}); } catch(e) { report('同键异文', {error:e.code}); }
const partial = queue.enqueue(event('partial'));
const change = store.mutate({scope:'project',workspace},mutation('sample'));
queue.update(partial.id,{status:'failed',effects:[{scope:'project',transaction:change.transaction}],error:'隔离模拟：提交后处理失败'});
report('部分成功', {pending:queue.list().total,commits:commits.list().items.map(x=>({id:x.id,status:x.status,entryId:x.entryId})),detail:store.changeDetail({scope:'project',workspace},change.transaction).status});
queue.retry(partial.id); queue.complete(partial.id);
report('重试完成释放', {pending:queue.list().total,commits:commits.list().total});
const second = queue.enqueue(event('other',other)); queue.complete(second.id);
store.mutate({scope:'user',workspace},mutation('shared'));
store.mutate({scope:'project',workspace:other},mutation('dependent',{links:[{kind:'requires',scope:'user',id:'shared'}]}));
try { maintenance.assertUnreferenced(workspace,'user','shared'); } catch(e) { report('清理后跨项目入链保护', {known:queue.knownWorkspaces().length,error:e.code}); }
report('全局提交分页', {total:commits.list().total,first:commits.list({limit:1}).items.map(x=>x.entryId),next:commits.list({offset:1,limit:1}).items.map(x=>x.entryId)});
const errors = maintenance.schedule(queue.all());
const sweep = queue.all().find(x=>x.event.maintenance);
queue.complete(sweep.event.id);
const checkpoint = queue.checkpoint(sweep.event.maintenance.scope,sweep.event.workspace);
maintenance.schedule(queue.all());
report('周期游标', {errors,checkpoint,completedScope:sweep.event.maintenance.scope,remainingSweeps:queue.all().map(x=>x.event.maintenance),known:queue.knownWorkspaces().length});
const legacy = queue.enqueue(event('legacy'));
queue.update(legacy.id,{status:'completed',completed:new Date().toISOString(),summary:'旧处理日志'.repeat(100)});
report('历史清理预览',queue.compactCompleted({dryRun:true}));
report('历史清理执行',queue.compactCompleted());
report('历史清理后', {retired:queue.get(legacy.id).state.retired,eventExists:fs.existsSync(runtime.file(`events/${legacy.id}.json`))});
const crashed = queue.enqueue(event('crash'));
const payload = queue.get(crashed.id).event.payloadHash;
const shard = crashed.id.slice(0,2);
runtime.write(`receipts/${shard}.json`,{...(runtime.read(`receipts/${shard}.json`)||{}),[crashed.id]:payload});
fs.unlinkSync(runtime.file(`jobs/${crashed.id}.json`));
queue.reconcile();
report('清理中断恢复', {retired:queue.get(crashed.id).state.retired,duplicate:queue.enqueue(event('crash')).duplicate,eventExists:fs.existsSync(runtime.file(`events/${crashed.id}.json`))});
report('隔离目录', {root});
