const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const repo = '/Users/caishilin/Desktop/personal/skills';
const callbacks = [];
const sandbox = { module: { exports: {} }, Buffer, setTimeout: (callback, ms) => { callbacks.push({ callback, ms }); return { unref() {} }; }, clearTimeout() {} };
vm.runInNewContext(fs.readFileSync(path.join(repo, 'bin/memory/live.js'), 'utf8'), sandbox);
const live = sandbox.module.exports;
const event = { workspace: '/isolated/a', id: 'first', session: 'session', task: null, messages: [{ role: 'user', text: 'visible input' }] };
live.start(event, 1);
live.observe(event.workspace, { type: 'message_update', assistantMessageEvent: { type: 'thinking_delta', delta: 'HIDDEN_CANARY' } });
live.observe(event.workspace, { type: 'message_end', message: { role: 'assistant', content: [{ type: 'thinking', thinking: 'HIDDEN_CANARY' }, { type: 'text', text: '公开结果' }] } });
live.observe(event.workspace, { type: 'tool_execution_start', toolName: 'read', toolCallId: 'call1', args: { path: '/isolated/file.md' } });
live.observe(event.workspace, { type: 'tool_execution_end', toolName: 'read', toolCallId: 'call1', result: { content: [{ type: 'text', text: 'Bearer secret-value sk-example-secret <img src=x onerror=alert(1)>' }, { type: 'image', data: 'HIDDEN_CANARY' }], details: { thinking: 'HIDDEN_CANARY' } } });
live.record(event.workspace, '记忆写入', { scope: 'project', transaction: 'example' });
const trace = live.get(event.workspace);
const wire = JSON.stringify(trace);
const observations = { kinds: trace.events.map(x => x.kind), hiddenCanaryAbsent: !wire.includes('HIDDEN_CANARY'), credentialsAbsent: !wire.includes('secret-value') && !wire.includes('sk-example-secret'), inputPresent: trace.input.includes('visible input'), otherWorkspaceAbsent: !live.get('/isolated/b').available };
for (let i = 0; i < 250; i++) live.record(event.workspace, '工具结果', 'x'.repeat(40000));
const bounded = live.get(event.workspace);
observations.bounds = { events: bounded.events.length, dropped: bounded.dropped, eventBytes: bounded.events.reduce((sum, x) => sum + Buffer.byteLength(JSON.stringify(x)), 0), largestTextBytes: Math.max(...bounded.events.map(x => Buffer.byteLength(x.text))), truncationVisible: bounded.events.every(x => x.text.includes('已截断')) };
live.finish(event.workspace, 'completed', 'done');
observations.retainedAfterFinish = live.get(event.workspace).status;
const expired = callbacks.at(-1);
observations.retentionMs = expired.ms;
live.start({ ...event, id: 'second' }, 2);
expired.callback();
observations.oldTimerPreservesNewBatch = live.get(event.workspace).event === 'second';
live.finish(event.workspace, 'failed', 'failure');
callbacks.at(-1).callback();
observations.expired = !live.get(event.workspace).available;
live.start(event, 1); live.clear();
observations.cleared = !live.get(event.workspace).available;
console.log(JSON.stringify(observations, null, 2));
fs.writeFileSync(path.join(__dirname, 'observation.json'), JSON.stringify(observations, null, 2) + '\n');
